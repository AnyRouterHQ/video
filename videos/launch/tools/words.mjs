#!/usr/bin/env node
/**
 * words — writes compositions/words.js from audio_meta.json, so every reveal is keyed to a
 * spoken word (`W(2, 'limited')`) and a new take re-times the film with no hand edits.
 *
 *   node tools/words.mjs        (run from videos/launch/, after tools/pace.mjs)
 */
import fs from 'node:fs';

const meta = JSON.parse(fs.readFileSync('audio_meta.json', 'utf8'));
const table = Object.fromEntries(meta.voices.map(v => [v.frame, v.words.map(w => [w.text.toLowerCase().replace(/[^\w$/.-]/g, '').replace(/\.$/, ''), w.start, w.end])]));
const js = `/* generated by tools/words.mjs from audio_meta.json — do not edit */
(() => {
  const WORDS = ${JSON.stringify(table)};
  /** Start (or end) of the nth spoken match of a word in a frame, in that frame's seconds. */
  window.W = (frame, word, nth = 1, edge = 'start') => {
    const key = word.toLowerCase().replace(/[^\\w$/.-]/g, '').replace(/\\.$/, '');
    const hits = (WORDS[frame] || []).filter(w => w[0] === key);
    const hit = hits[nth - 1];
    if (!hit) throw new Error(\`no word "\${word}" #\${nth} in frame \${frame}\`);
    return edge === 'end' ? hit[2] : hit[1];
  };
})();
`;
fs.writeFileSync('compositions/words.js', js);
console.log(`compositions/words.js: ${Object.values(table).reduce((n, w) => n + w.length, 0)} words in ${Object.keys(table).length} frames`);
